 // Convert Array to String

 // use .join() method to convert an array to a string. The join() method joins all elements of an array into a string. You can specify the separator to use between elements.
 
 const arr = ["Akash", "Babu", "Kushwah"];
const str = arr.join(" "); // Joining with space

console.log(str);
// Output: "Akash Babu Kushwah"

// Using toString() The .toString() method converts an array into a comma-separated string.

const str2 = arr.toString(); // Joining with space
console.log(str2);
